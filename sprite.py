def text_to_sprite(chars):
    """Convert text characters to index numbers in the font sprite buffer"""
    chars = chars.upper()
    buf = []
    for i in range(len(chars)):
        if ord(chars[i]) >= ord(' ') and ord(chars[i]) <= ord('~'):
            buf.append(ord(chars[i]) - ord(' '))
        else:
            buf.append(-1)
    return buf


def drawtext(text, font, scale):
    """Draw text characters on a pygame surface"""
    height = (CHARHEIGHT + 1)
    width = max(1, (len(text) * (CHARWIDTH + CHARSPACING) - CHARSPACING))
    charbuf = text_to_sprite(text)
    surf = pygame.Surface((width, height), pygame.SRCALPHA)
    for i in range(len(charbuf)):
        surf.blit(font[charbuf[i]], (i * (CHARWIDTH + CHARSPACING), 1))
    surf = pygame.transform.scale(surf, (width * scale, height * scale))
    return surf


